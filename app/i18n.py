def get_lang():
    import streamlit as st
    return st.session_state.get("lang", "EN")


def t(key, lang=None, **kwargs):
    code = (lang or get_lang()).lower()
    text = TEXT.get(code, TEXT["en"]).get(key) or TEXT["en"].get(key, key)
    return text.format(**kwargs) if kwargs else text


def language_selector():
    import streamlit as st
    if "lang" not in st.session_state:
        st.session_state["lang"] = "EN"
    st.sidebar.radio(t("lang.label"), LANGS, key="lang", horizontal=True)


def type_label(code, lang=None):
    return t(f"type.{code}", lang) if f"type.{code}" in TEXT["en"] else str(code)


def severity_label(code, lang=None):
    return t(f"severity.{code}", lang) if f"severity.{code}" in TEXT["en"] else str(code)


def column_labels(columns, lang=None):
    return {c: t(f"col.{c}", lang) for c in columns if f"col.{c}" in TEXT["en"]}
